# typecasting is a process of converting one data type into another data type. 
# In Python, we can use built-in functions to perform typecasting.
# python support wide variety of data types, and we can convert between them using typecasting functions.
# int(),float(),str(),bool(),list(),tuple(),dict() are some of the commonly 
# used typecasting functions in python.
# there are two types of typecasting in python, implicit and explicit typecasting.


# a = "5"
a = 1
# b = "6"
b = 2
print (int(a) + int(b)) # explicit typecasting
print (a + b) # implicit typecasting
name = "Mujeeb"
age = 25
print(str(name) + str(age)) # explicit typecasting
print(type(name)) # implicit typecasting